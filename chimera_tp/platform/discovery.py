class AppRegistry:
    """Persistent + live registry of linked & attached applications across the host."""

    def __init__(self, registry_path: Path) -> None:
        self.registry_path = Path(registry_path)
        self._lock = threading.Lock()
        self._linked: dict[str, dict[str, Any]] = {}
        self._live: dict[str, dict[str, Any]] = {}
        self._load()

    def _load(self) -> None:
        try:
            if self.registry_path.is_file():
                raw = json.loads(self.registry_path.read_text(encoding="utf-8"))
                if isinstance(raw, dict):
                    self._linked = {
                        str(k): dict(v) for k, v in raw.items() if isinstance(v, dict)
                    }
        except Exception:
            self._linked = {}

    def _save_locked(self) -> None:
        _atomic_write_text(
            self.registry_path,
            json.dumps(self._linked, indent=2, ensure_ascii=False),
        )

    def link_entry(self, app_name: str, info: dict[str, Any]) -> dict[str, Any]:
        name = _sanitize_app_name(app_name)
        now = datetime.now().astimezone().isoformat(timespec="seconds")
        with self._lock:
            prev = self._linked.get(name, {})
            merged = {
                **prev,
                **info,
                "app": name,
                "linked_at": prev.get("linked_at", now),
                "updated_at": now,
            }
            self._linked[name] = merged
            self._save_locked()
            return dict(merged)

    def unlink_entry(self, app_name: str) -> bool:
        name = _sanitize_app_name(app_name)
        with self._lock:
            existed = name in self._linked
            self._linked.pop(name, None)
            self._live.pop(name, None)
            if existed:
                self._save_locked()
            return existed

    def register_live(self, payload: dict[str, Any]) -> dict[str, Any]:
        name = _sanitize_app_name(str(payload.get("app") or "unnamed"))
        now = time.time()
        with self._lock:
            prev = self._live.get(name, {})
            entry = {
                "app": name,
                "pid": int(payload.get("pid") or prev.get("pid") or 0),
                "cwd": str(payload.get("cwd") or prev.get("cwd") or ""),
                "port": int(payload.get("port") or prev.get("port") or 0),
                "domain": str(payload.get("domain") or prev.get("domain") or f"{name}.chimera.local"),
                "qos": str(payload.get("qos") or prev.get("qos") or "interactive"),
                "needs": list(payload.get("needs") or prev.get("needs") or ["egress", "pulse"]),
                "sdk_version": str(payload.get("sdk_version") or prev.get("sdk_version") or "16.0"),
                "attach_mode": str(payload.get("attach_mode") or prev.get("attach_mode") or "sdk"),
                "registered_at": prev.get("registered_at") or datetime.now().astimezone().isoformat(timespec="seconds"),
                "last_seen_epoch": now,
                "last_seen": datetime.now().astimezone().strftime("%H:%M:%S"),
                "heartbeats": int(prev.get("heartbeats", 0)) + 1,
            }
            self._live[name] = entry
            return dict(entry)

    def list_apps(self, stale_after_s: float = 180.0) -> list[dict[str, Any]]:
        now = time.time()
        with self._lock:
            names = sorted(set(self._linked.keys()) | set(self._live.keys()))
            out: list[dict[str, Any]] = []
            for name in names:
                lnk = self._linked.get(name, {})
                lv = self._live.get(name)
                alive = False
                if lv is not None:
                    age = now - float(lv.get("last_seen_epoch", 0.0))
                    pid = int(lv.get("pid", 0))
                    alive = age <= stale_after_s and (pid <= 0 or _pid_alive(pid))
                item = {
                    "app": name,
                    "domain": (lv or {}).get("domain") or lnk.get("domain") or f"{name}.chimera.local",
                    "path": lnk.get("path") or (lv or {}).get("cwd") or "",
                    "port": int((lv or {}).get("port") or lnk.get("port") or 0),
                    "qos": (lv or {}).get("qos") or lnk.get("qos") or "interactive",
                    "needs": (lv or {}).get("needs") or lnk.get("needs") or ["egress", "pulse"],
                    "linked": bool(lnk),
                    "online": alive,
                    "pid": int((lv or {}).get("pid") or 0) if alive else 0,
                    "attach_mode": (lv or {}).get("attach_mode") or ("linked" if lnk else "unknown"),
                    "last_seen": (lv or {}).get("last_seen") or lnk.get("updated_at") or "",
                    "heartbeats": int((lv or {}).get("heartbeats") or 0),
                }
                out.append(item)
            return out

    def match_cwd(self, cwd: str | Path) -> dict[str, Any] | None:
        try:
            norm = os.path.normcase(os.path.abspath(str(cwd)))
        except Exception:
            return None
        with self._lock:
            for item in self._linked.values():
                p = item.get("path")
                if not p:
                    continue
                p_norm = os.path.normcase(os.path.abspath(str(p)))
                if norm == p_norm or norm.startswith(p_norm + os.sep):
                    return dict(item)
        return None


def _sanitize_app_name(raw: str) -> str:
    cleaned = re.sub(r"[^a-zA-Z0-9_\-.]+", "-", str(raw).strip().lower()).strip("-.")
    return cleaned[:48] or "unnamed-app"


def _pid_alive(pid: int) -> bool:
    if pid <= 0:
        return False
    if os.name == "nt":
        try:
            import ctypes

            SYNCHRONIZE = 0x00100000
            PROCESS_QUERY_LIMITED_INFORMATION = 0x1000
            h = ctypes.windll.kernel32.OpenProcess(
                SYNCHRONIZE | PROCESS_QUERY_LIMITED_INFORMATION, False, int(pid)
            )
            if not h:
                return False
            try:
                code = ctypes.c_ulong(0)
                if ctypes.windll.kernel32.GetExitCodeProcess(h, ctypes.byref(code)):
                    return code.value == 259  # STILL_ACTIVE
                return True
            finally:
                ctypes.windll.kernel32.CloseHandle(h)
        except Exception:
            return True
    try:
        os.kill(pid, 0)
        return True
    except ProcessLookupError:
        return False
    except PermissionError:
        return True
    except Exception:
        return False


def detect_project_profile(project_dir: Path) -> dict[str, Any]:
    root = Path(project_dir).resolve()
    name = _sanitize_app_name(root.name)
    lang = "unknown"
    framework = "generic"
    port_hint = 0
    if (root / "pyproject.toml").exists() or (root / "requirements.txt").exists() or list(root.glob("*.py")):
        lang = "python"
    elif (root / "package.json").exists():
        lang = "node"
    elif (root / "Cargo.toml").exists():
        lang = "rust"
    elif (root / "go.mod").exists():
        lang = "go"

    # Quick non-invasive scan of manifest/README/config for framework & port hints
    for fname in ("package.json", "pyproject.toml", "requirements.txt", ".env.example"):
        fp = root / fname
        if fp.is_file():
            try:
                txt = fp.read_text(encoding="utf-8", errors="ignore")[:8192].lower()
                if "fastapi" in txt or "uvicorn" in txt:
                    framework = "fastapi"
                elif "flask" in txt:
                    framework = "flask"
                elif "next" in txt:
                    framework = "nextjs"
                elif "express" in txt:
                    framework = "express"
                m = re.search(r"(?:port|listen)\s*[=:]\s*(\d{4,5})", txt)
                if m and port_hint == 0:
                    p = int(m.group(1))
                    if 1024 <= p <= 65535:
                        port_hint = p
            except OSError:
                pass

    return {
        "app": name,
        "path": str(root),
        "language": lang,
        "framework": framework,
        "port": port_hint,
        "domain": f"{name}.chimera.local",
        "qos": "interactive",
        "needs": ["egress", "membrane-cache", "pulse", "search"],
    }


def link_project(
    project_dir: str | Path,
    app_name: str | None = None,
    port: int | None = None,
    qos: str = "interactive",
    registry_path: Path | None = None,
) -> dict[str, Any]:
    root = Path(project_dir).resolve()
    root.mkdir(parents=True, exist_ok=True)
    prof = detect_project_profile(root)
    if app_name:
        prof["app"] = _sanitize_app_name(app_name)
        prof["domain"] = f"{prof['app']}.chimera.local"
    if port is not None and int(port) > 0:
        prof["port"] = int(port)
    prof["qos"] = qos

    manifest_path = root / "chimera.manifest.json"
    if manifest_path.is_file():
        try:
            existing = json.loads(manifest_path.read_text(encoding="utf-8"))
            if isinstance(existing, dict):
                prof = {**prof, **existing}
                if app_name:
                    prof["app"] = _sanitize_app_name(app_name)
                if port is not None and int(port) > 0:
                    prof["port"] = int(port)
        except Exception:
            pass

    manifest = {
        "schema": "chimera.manifest.v1",
        "app": prof["app"],
        "domain": prof["domain"],
        "language": prof["language"],
        "framework": prof["framework"],
        "port": prof["port"],
        "qos": prof["qos"],
        "needs": prof["needs"],
        "auto_attach": True,
    }
    _atomic_write_text(manifest_path, json.dumps(manifest, indent=2, ensure_ascii=False))

    reg = AppRegistry(registry_path or (chimera_home_dir() / "apps.json"))
    entry = reg.link_entry(
        manifest["app"],
        {
            "path": str(root),
            "manifest": str(manifest_path),
            "domain": manifest["domain"],
            "port": manifest["port"],
            "qos": manifest["qos"],
            "needs": manifest["needs"],
            "language": manifest["language"],
        },
    )
    return {"ok": True, "manifest_path": str(manifest_path), "manifest": manifest, "entry": entry}


