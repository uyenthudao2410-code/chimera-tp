class PassivePortScanner:
    """Low-overhead (<0.2% CPU, cached) local listening port discovery."""

    def __init__(self, cache_ttl_s: float = 10.0) -> None:
        self._ttl = float(cache_ttl_s)
        self._lock = threading.Lock()
        self._ts = 0.0
        self._cached: list[dict[str, Any]] = []

    def scan(self, exclude_ports: set[int] | None = None, force: bool = False) -> list[dict[str, Any]]:
        now = time.monotonic()
        with self._lock:
            if (not force) and self._cached and (now - self._ts) < self._ttl:
                items = list(self._cached)
            else:
                items = self._probe_os()
                self._cached = items
                self._ts = now
        excl = exclude_ports or set()
        return [it for it in items if int(it.get("port", 0)) not in excl]

    def _probe_os(self) -> list[dict[str, Any]]:
        found: dict[int, dict[str, Any]] = {}
        try:
            if os.name == "nt":
                out = subprocess.check_output(
                    ["netstat", "-ano", "-p", "TCP"],
                    stderr=subprocess.DEVNULL,
                    timeout=3.0,
                    text=True,
                )
                for line in out.splitlines():
                    parts = line.split()
                    if len(parts) >= 5 and parts[3].upper() == "LISTENING":
                        local = parts[1]
                        pid = int(parts[4]) if parts[4].isdigit() else 0
                        m = re.search(r":(\d+)$", local)
                        if m:
                            port = int(m.group(1))
                            if 1024 <= port <= 65000 and port not in found:
                                found[port] = {"port": port, "bind": local, "pid": pid, "process": ""}
            else:
                out = subprocess.check_output(
                    ["ss", "-tlnp"],
                    stderr=subprocess.DEVNULL,
                    timeout=3.0,
                    text=True,
                )
                for line in out.splitlines()[1:]:
                    parts = line.split()
                    if len(parts) >= 4:
                        local = parts[3]
                        m = re.search(r":(\d+)$", local)
                        if not m:
                            continue
                        port = int(m.group(1))
                        if not (1024 <= port <= 65000) or port in found:
                            continue
                        proc_m = re.search(r'"([^"]+)",pid=(\d+)', line)
                        proc = proc_m.group(1) if proc_m else ""
                        pid = int(proc_m.group(2)) if proc_m else 0
                        found[port] = {"port": port, "bind": local, "pid": pid, "process": proc}
        except Exception:
            pass
        return sorted(found.values(), key=lambda x: x["port"])


