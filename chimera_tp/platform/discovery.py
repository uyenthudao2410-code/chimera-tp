def chimera_home_dir() -> Path:
    return Path.home() / ".chimera"


def runtime_beacon_paths(ops_dir: Path, ephemeral: bool = False) -> list[Path]:
    paths: list[Path] = [Path(ops_dir) / "runtime.json"]
    if ephemeral:
        return paths
    home_rt = chimera_home_dir() / "runtime.json"
    if home_rt not in paths:
        paths.append(home_rt)
    if os.name == "nt":
        local_app = os.environ.get("LOCALAPPDATA")
        if local_app:
            p = Path(local_app) / "chimera" / "runtime.json"
            if p not in paths:
                paths.append(p)
    else:
        run_dir = Path("/run/chimera")
        try:
            if run_dir.exists() and os.access(run_dir, os.W_OK):
                paths.append(run_dir / "runtime.json")
        except OSError:
            pass
    return paths


def _atomic_write_text(path: Path, text: str) -> bool:
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(path.suffix + f".tmp.{os.getpid()}")
        tmp.write_text(text, encoding="utf-8")
        os.replace(tmp, path)
        return True
    except OSError:
        return False


def discover_runtime_file(explicit_path: str | Path | None = None) -> dict[str, Any] | None:
    candidates: list[Path] = []
    if explicit_path:
        candidates.append(Path(explicit_path))
    env_rt = os.environ.get("CHIMERA_RUNTIME", "").strip()
    if env_rt:
        candidates.append(Path(env_rt))
    candidates.append(chimera_home_dir() / "runtime.json")
    if os.name == "nt":
        local_app = os.environ.get("LOCALAPPDATA", "").strip()
        if local_app:
            candidates.append(Path(local_app) / "chimera" / "runtime.json")
    else:
        candidates.append(Path("/run/chimera/runtime.json"))

    seen: set[str] = set()
    for p in candidates:
        key = str(p)
        if key in seen:
            continue
        seen.add(key)
        try:
            if p.is_file():
                data = json.loads(p.read_text(encoding="utf-8"))
                if isinstance(data, dict) and data.get("anchor_url"):
                    data["_runtime_path"] = str(p)
                    return data
        except Exception:
            continue
    return None


